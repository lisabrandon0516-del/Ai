def wrap_alaska_lon(lon: float) -> float:
    """Shift antimeridian Aleutians into the Alaska inset's western hemisphere."""
    try:
        value = float(lon)
    except (TypeError, ValueError):
        return 0.0
    return value - 360.0 if value > 0 else value


def region_for_lonlat(lon: float, lat: float) -> str:
    """Return 'AK', 'HI', or 'CONUS' for a WGS84 point (territories stay CONUS)."""
    try:
        lon = float(lon)
        lat = float(lat)
    except (TypeError, ValueError):
        return "CONUS"
    if -161.8 <= lon <= -154.0 and 18.7 <= lat <= 22.6:
        return "HI"
    wrapped = wrap_alaska_lon(lon)
    if -188.0 <= wrapped <= -129.5 and 51.0 <= lat <= 71.8:
        return "AK"
    return "CONUS"



# Spherical Albers equal-area (std parallels, central meridian, origin), degrees.
# Cheap USA-style projections so the dashboard map keeps a true land aspect
# without a GIS dependency. Scale is arbitrary; callers fit the result to a rect.
ALBERS_CONUS = (29.5, 45.5, -96.0, 23.0)  # EPSG:5070 parallels
ALBERS_AK = (55.0, 65.0, -154.0, 50.0)    # EPSG:3338 parallels
ALBERS_HI = (8.0, 18.0, -157.0, 13.0)


def _albers_setup(params: tuple[float, float, float, float]) -> tuple[float, float, float, float]:
    lat1, lat2, lon0, lat0 = params
    phi1, phi2, lam0, phi0 = (math.radians(lat1), math.radians(lat2), math.radians(lon0), math.radians(lat0))
    n = 0.5 * (math.sin(phi1) + math.sin(phi2))
    if abs(n) < 1e-12:
        n = 1e-12
    c = math.cos(phi1) ** 2 + 2 * n * math.sin(phi1)
    rho0 = math.sqrt(max(0.0, c - 2 * n * math.sin(phi0))) / n
    return n, c, rho0, lam0


_ALBERS_CACHE: dict[tuple[float, float, float, float], tuple[float, float, float, float]] = {}


def project_albers(lon: float, lat: float, params: tuple[float, float, float, float] = ALBERS_CONUS) -> tuple[float, float]:
    """Project WGS84 lon/lat with a spherical Albers equal-area conic."""
    setup = _ALBERS_CACHE.get(params)
    if setup is None:
        setup = _albers_setup(params)
        _ALBERS_CACHE[params] = setup
    n, c, rho0, lam0 = setup
    phi = math.radians(float(lat))
    lam = math.radians(float(lon))
    rho = math.sqrt(max(0.0, c - 2 * n * math.sin(phi))) / n
    theta = n * (lam - lam0)
    return rho * math.sin(theta), rho0 - rho * math.cos(theta)


def albers_params_for(region: str) -> tuple[float, float, float, float]:
    if region == "AK":
        return ALBERS_AK
    if region == "HI":
        return ALBERS_HI
    return ALBERS_CONUS


def project_region(lon: float, lat: float, region: str = "CONUS") -> tuple[float, float]:
    if region == "AK":
        lon = wrap_alaska_lon(lon)
    return project_albers(lon, lat, albers_params_for(region))


def _pad_bounds(minx: float, miny: float, maxx: float, maxy: float, frac: float = 0.035) -> tuple[float, float, float, float]:
    span_x = maxx - minx
    span_y = maxy - miny
    return (minx - span_x * frac, miny - span_y * frac, maxx + span_x * frac, maxy + span_y * frac)


def _projected_extent(abbrs, region: str, pad: float = 0.035) -> tuple[float, float, float, float]:
    xs: list[float] = []
    ys: list[float] = []
    for abbr in abbrs:
        for ring in STATE_RINGS.get(abbr) or []:
            for lon, lat in ring:
                x, y = project_region(lon, lat, region)
                xs.append(x)
                ys.append(y)
    if not xs:
        return (-1.0, -1.0, 1.0, 1.0)
    return _pad_bounds(min(xs), min(ys), max(xs), max(ys), frac=pad)


_REGION_EXTENT: dict[str, tuple[float, float, float, float]] = {}


def region_extent(region: str) -> tuple[float, float, float, float]:
    """Padded projected bounds (minx, miny, maxx, maxy) for CONUS, AK, or HI."""
    cached = _REGION_EXTENT.get(region)
    if cached is None:
        if region == "AK":
            cached = _projected_extent(("AK",), "AK")
        elif region == "HI":
            cached = _projected_extent(("HI",), "HI")
        else:
            cached = _projected_extent(CONTERMINOUS, "CONUS")
        _REGION_EXTENT[region] = cached
    return cached


def region_aspect(region: str = "CONUS") -> float:
    minx, miny, maxx, maxy = region_extent(region)
    height = max(maxy - miny, 1e-9)
    return (maxx - minx) / height
